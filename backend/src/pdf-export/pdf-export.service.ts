import { Injectable } from '@nestjs/common';
import PDFDocument from 'pdfkit';
import { SoapNote, Patient, Consultation } from '../../generated/prisma/client';

interface SoapNotePdfInput {
  soapNote: SoapNote;
  patient: Patient;
  consultation: Consultation;
  doctorName: string;
}

@Injectable()
export class PdfExportService {
  async generateSoapNotePdf(input: SoapNotePdfInput): Promise<Buffer> {
    const { soapNote, patient, consultation, doctorName } = input;

    return new Promise((resolve, reject) => {
      const doc = new PDFDocument({ margin: 50 });
      const chunks: Buffer[] = [];

      doc.on('data', (chunk) => chunks.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', reject);

      doc.fontSize(18).font('Helvetica-Bold').text('MedScribe AI', { align: 'left' });
      doc.fontSize(10).font('Helvetica').fillColor('#666').text('SOAP Note — Approved Medical Record', { align: 'left' });
      doc.moveDown(1.5);

      doc.strokeColor('#dddddd').lineWidth(1).moveTo(50, doc.y).lineTo(545, doc.y).stroke();
      doc.moveDown(1);

      doc.fillColor('#000000').fontSize(11).font('Helvetica-Bold').text('Patient: ', { continued: true });
      doc.font('Helvetica').text(`${patient.lastName}, ${patient.firstName}`);

      doc.font('Helvetica-Bold').text('Date of Birth: ', { continued: true });
      doc.font('Helvetica').text(patient.dateOfBirth.toLocaleDateString());

      doc.font('Helvetica-Bold').text('Consultation Date: ', { continued: true });
      doc.font('Helvetica').text(consultation.occurredAt.toLocaleString());

      doc.font('Helvetica-Bold').text('Approving Clinician: ', { continued: true });
      doc.font('Helvetica').text(doctorName);

      doc.font('Helvetica-Bold').text('Approved: ', { continued: true });
      doc.font('Helvetica').text(soapNote.approvedAt ? soapNote.approvedAt.toLocaleString() : 'N/A');

      doc.moveDown(1.5);

      this.addSection(doc, 'Subjective', soapNote.subjectiveContent, soapNote.subjectiveNotMentioned);
      this.addSection(doc, 'Objective', soapNote.objectiveContent, soapNote.objectiveNotMentioned);
      this.addSection(doc, 'Assessment', soapNote.assessmentContent, soapNote.assessmentNotMentioned);
      this.addSection(doc, 'Plan', soapNote.planContent, soapNote.planNotMentioned);

      doc.moveDown(1);
      doc.strokeColor('#dddddd').lineWidth(1).moveTo(50, doc.y).lineTo(545, doc.y).stroke();
      doc.moveDown(0.5);
      doc.fontSize(8).fillColor('#999999').text(
        `Generated by MedScribe AI. This document reflects version ${soapNote.version} of the SOAP note for this consultation, approved by the clinician of record.`,
        { align: 'left' },
      );

      doc.end();
    });
  }

  private addSection(doc: PDFKit.PDFDocument, title: string, content: string, notMentioned: string[]): void {
    doc.fontSize(13).font('Helvetica-Bold').fillColor('#1e40af').text(title);
    doc.moveDown(0.3);
    doc.fontSize(10.5).font('Helvetica').fillColor('#000000').text(content || 'No content recorded.', {
      align: 'left',
      lineGap: 2,
    });

    if (notMentioned.length > 0) {
      doc.moveDown(0.3);
      doc.fontSize(9).font('Helvetica-Oblique').fillColor('#92400e').text(
        `Not mentioned: ${notMentioned.join(', ')}`,
      );
    }

    doc.moveDown(1);
  }
}